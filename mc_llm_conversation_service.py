def publish(kind: str, key: Key | None = None, **payload) -> None:
    """Tell every open page that something happened. Never fails a caller.

    Display publishing fails *open* (specification 4.4) and safety fails
    closed, and this is the open half: a save that succeeded is a save that
    succeeded whether or not anybody could be told about it. A publish that
    raises here would make a successful write look like a failed one, which is
    the one thing worse than a window that has to be refreshed.
    """
    try:
        import mc_llm_conversation_feed as feed

        feed.publish(kind, key, **payload)
    except Exception:
        logger.debug("Model Chain: could not publish a conversation event", exc_info=True)


def reset() -> None:
    """Forget every operation record. For the tests, and for a UI reload."""
    registry.reset()
