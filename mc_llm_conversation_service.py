def _create_thread(envelope: Envelope) -> dict:
    store = chats()
    character = envelope.conversation.character if envelope.conversation else ""
    if not str(character).strip():
        raise Refused(INVALID_INPUT, "Choose a character first.")
    identifier = store.new(character).identifier
    key = Key(character=character, thread_id=identifier)
    receipt = Receipt(operation_id=envelope.operation_id, action=envelope.action,
                      issued_at=envelope.issued_at, payload_digest=envelope.digest(),
                      resulting_conversation=identifier)

    def build():
        from prompt_master.chat.history import ASSISTANT, Conversation

        now = time.time()
        conversation = Conversation(identifier=identifier, character=character,
                                    created=now, updated=now)
        text = _greeting(character)
        if text.strip():
            conversation.append(ASSISTANT, text)
        return conversation

    committed = store_module.create(store, key, build, receipt=receipt)
    publish(CONVERSATION_CHANGED, key, revision=committed.revision, kind_detail="created")
    return _accepted(envelope, key, committed.revision)


def _greeting(character: str) -> str:
    from prompt_master.chat.prompt import greeting_text

    try:
        from prompt_master.chat.characters import load_persona

        import mc_llm_paths

        return greeting_text(_characters().load(character),
                             load_persona(mc_llm_paths.app_paths()))
    except Exception:
        logger.debug("Model Chain: could not read %s's greeting", character, exc_info=True)
        return ""


def _delete_thread(envelope: Envelope) -> dict:
    store = chats()
    key = envelope.conversation
    wanted = envelope.payload.get("confirm_title")
    if wanted is not None:
        conversation, _ = store_module.read(store, key)
        if conversation.title != wanted:
            raise Refused(STALE_REVISION, "This thread was renamed. Look again before "
                                          "deleting it.")
    receipt = Receipt(operation_id=envelope.operation_id, action=envelope.action,
                      issued_at=envelope.issued_at, payload_digest=envelope.digest())
    store_module.remove(store, key, envelope.expected_revision, receipt=receipt)
    publish(THREAD_DELETED, key)
    return _accepted(envelope, key, 0)


def _branch(envelope: Envelope) -> dict:
    """Copy a thread through one message into a new one. Two files, one lock order.

    The source is read and left alone -- a branch never writes to the thread it
    came from, which is what makes every one of these actions reversible by
    simply going back to it.
    """
    store = chats()
    key = envelope.conversation
    index = envelope.target_index
    committed = _branch_from(store, key, envelope.expected_revision, index,
                             envelope.operation_id, envelope.issued_at, envelope.digest())
    branched = committed.conversation
    made = Key(character=branched.character, thread_id=branched.identifier)
    publish(THREAD_CREATED, made, revision=committed.revision)
    return _accepted(envelope, made, committed.revision)


def _branch_from(store, key: Key, expected, index: int, operation_id: str,
                 issued_at: str, digest: str):
    """The shared half of every branching action. Returns the new conversation.

    Used by Branch from here, by mid-thread Regenerate, by Continue on an
    earlier reply and by Send again from here -- four buttons that used to be
    four pieces of nearly-identical code, one of which deleted the rest of the
    conversation (specification 6.3).
    """
    source, raw = store_module.read(store, key)
    if source.damaged:
        raise Refused(STORAGE_EXTERNALLY_CHANGED, "Conversation metadata needs repair.")
    current = store_module.token_of(source, raw)
    if not store_module.matches(expected, current):
        raise Refused(STALE_REVISION, "This conversation changed in another window. "
                                      "Your draft is safe.", current_revision=current)
    owner = store_module.active_writer(store, key)
    if owner:
        raise Refused(THREAD_BUSY, "Reply in progress. Stop it before changing this "
                                   "conversation.", operation_id=owner.get("operation_id"))
    if index is None or not -1 <= index < len(source.messages):
        raise Refused(STALE_REVISION, "That message is not there any more.")

    identifier = store.new(key.character).identifier
    made = Key(character=key.character, thread_id=identifier)
    receipt = Receipt(operation_id=operation_id, action=BRANCH, issued_at=issued_at,
                      payload_digest=digest, resulting_conversation=identifier)
    return store_module.create(store, made,
                               lambda: source.branch(index, identifier), receipt=receipt)


def _stop(envelope: Envelope) -> dict:
    import mc_llm_conversation_ops as ops

    wanted = envelope.payload.get("operation_id") or ""
    stopped = ops.stop(wanted)
    return {"ok": True, "operation_id": envelope.operation_id, "persisted": False,
            "duplicate": False, "phase": "stopping" if stopped else "unknown",
            "server_epoch": SERVER_EPOCH, "stopped": wanted}


