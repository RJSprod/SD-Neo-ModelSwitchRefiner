"""One door into the conversation. Every writer comes through here.

The tab's Gradio callbacks and the assistant's HTTP routes are two ways of
saying the same sentences, and this module is where they become the same
sentence. A command arrives as an envelope — what to do, to which message of
which conversation, and *what revision the person was looking at when they
decided* — and leaves as an outcome that either happened exactly once or did
not happen at all.

Why an envelope rather than arguments
-------------------------------------
Three of its fields exist because of failures that have no other answer.

``expected_revision`` is the one the whole design turns on. An index alone is
not a target: "delete message 4" means a different message once another window
has inserted one, and the old code would have deleted whatever was at 4 by
then. Index and revision are validated *together*, under the conversation's
lock, so a target either names what the person saw or names nothing.

``operation_id`` is minted by the client before the first transmission and
never re-minted. A send whose acknowledgement is lost is retried with the same
id and produces one message and one inference — the second attempt finds the
receipt and returns the first attempt's answer. The same id with different
content is a bug in the caller and is refused rather than guessed at.

``server_epoch`` catches the case that looks like all the others and is not: a
restarted server. Operation ids from the old process mean nothing to the new
one, and a client that does not know it restarted would retry into a registry
that has never heard of its request. The epoch changes on restart, so it is
told.

What this module does not do
----------------------------
It does not build prompts, choose samplers, load models, decide who gets the
card, or speak. Those all stayed exactly where they were. What moved here is
only the deciding of whether a change is allowed and the recording of what
happened — which is the part that was never anywhere at all.
"""

from __future__ import annotations

import hashlib
import json
import logging
import re
import threading
import time
