logger = logging.getLogger("model_chain")
"""Handler is attached once, in mc_memory."""

PROTOCOL_VERSION = 2

SERVER_EPOCH = uuid.uuid4().hex
"""This process's boot identity. Nonsecret, and regenerated by a restart.

Not a credential and never treated as one -- it is in every event and every
response, and its whole job is to let a page notice that the process it was
talking to is not the process it is talking to now.
"""

MAX_TEXT_BYTES = 256 * 1024
"""The largest message this will accept, in UTF-8 bytes. Refused, never cut.

Silent truncation is the failure mode this number exists to prevent: a message
that arrives shortened is a message the person did not write, and they find out
by reading their own conversation later.
"""

TERMINAL_RETENTION = 1800.0
"""How long a finished operation's outcome is remembered. Thirty minutes.

Long enough for any retry a dropped connection can produce, short enough that a
day of conversation is not also a day of receipts in RAM. The file's own
receipts outlive this and answer a retry after a restart.
"""

MAX_TERMINAL_RECORDS = 1000
"""Per scope. When full, new operations are refused rather than old ones evicted.

The order matters and is the specification's (6.4). Evicting the youngest
record to admit a new one would mean the retry most likely to arrive is the one
whose answer was just thrown away.
"""

