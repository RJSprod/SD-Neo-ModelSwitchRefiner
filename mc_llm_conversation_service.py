STATUS = {
    INVALID_INPUT: 400,
    UNSUPPORTED_PROTOCOL: 400,
    AUTH_REQUIRED: 401,
    FORBIDDEN: 403,
    NOT_FOUND: 404,
    STALE_REVISION: 409,
    THREAD_BUSY: 409,
    OPERATION_ID_REUSED: 409,
    SERVER_RESTARTED: 409,
    ATTACHMENT_NOT_READY: 422,
    ATTACHMENT_EXPIRED: 422,
    VISION_UNAVAILABLE: 422,
    STORAGE_EXTERNALLY_CHANGED: 422,
    SAVE_FAILED: 500,
    SERVICE_UNAVAILABLE: 503,
}
"""Code to HTTP status. 413 is applied by the size check itself, which is the
one refusal that has to happen before the body is parsed."""

RETRYABLE = (SAVE_FAILED, SERVICE_UNAVAILABLE)
"""Which refusals are worth pressing the same button again for.

A stale revision is not one of them: the answer is a fresh snapshot and a new
decision, and a client that retried it automatically would be a client that
overwrites another window as soon as it is patient enough.
"""


class Refused(Exception):
    """A command that will not be run, with the reason a person can read."""

    def __init__(self, code: str, message: str, **detail):
        super().__init__(message)
        self.code = code
        self.message = message
        self.detail = detail

    @property
    def status(self) -> int:
        return STATUS.get(self.code, 400)

    def payload(self) -> dict:
        found = {"code": self.code, "message": self.message,
                 "retryable": self.code in RETRYABLE}
        found.update(self.detail)
        return found


