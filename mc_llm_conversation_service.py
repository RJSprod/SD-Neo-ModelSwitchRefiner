def snapshot(character: str, thread_id: str, selection_epoch: str = "",
             cursor: int | None = None) -> dict:
    """The whole displayed truth about one conversation, at one moment.

    Read-only, and the *only* way a second window learns what the first one
    did. It carries no filesystem path: an attachment is a name, an availability
    and the serving route the tab already uses, because a browser that is handed
    a path is a browser that can be persuaded to ask for a different one.
    """
    store = chats()
    key = Key(character=character or "", thread_id=thread_id or "")
    import mc_llm_conversation_feed as feed

    found: dict = {
        "protocol_version": PROTOCOL_VERSION,
        "capabilities": capabilities(),
        "sync": {"server_epoch": SERVER_EPOCH,
                 "stream_cursor": feed.cursor() if cursor is None else int(cursor)},
        "selection_epoch": selection_epoch or "",
        "operation": None,
    }
    if not key.valid:
        found["conversation"] = None
        found["messages"] = []
        return found
    try:
        conversation, raw = store_module.read(store, key)
    except StoreRefusal as refusal:
        found["conversation"] = None
        found["messages"] = []
        found["error"] = _from_store(refusal).payload()
        return found

    found["conversation"] = {
        "character": conversation.character,
        "thread_id": conversation.identifier,
        "title": conversation.title,
        "revision": store_module.token_of(conversation, raw),
        "response_prefix": conversation.response_prefix,
        "updated": conversation.updated,
        "damaged": bool(conversation.damaged),
    }
    found["messages"] = [_message_view(index, message)
                         for index, message in enumerate(conversation.messages)]

    found["threads"] = threads(character)
    found["characters"] = character_names()

    import mc_llm_conversation_ops as ops

    running = ops.for_conversation(key)
    if running is not None:
        found["operation"] = running.describe()
    found["recovery"] = [item.describe() for item in ops.recoverable(key)]
    return found


def _message_view(index: int, message) -> dict:
    import mc_llm_attachments

    attachment = None
    if message.attached:
        available = True
        if message.image_path:
            try:
                available = mc_llm_attachments.locate(message.image_path) is not None
            except Exception:
                available = False
        attachment = {"name": message.image_name or "", "available": bool(available),
                      "inline": bool(message.image and not message.image_path)}
        if message.image_path:
            attachment["url"] = mc_llm_attachments.serving_url(message.image_path)
    return {"index": index, "role": message.role, "versions": list(message.versions),
            "active": message.active, "text": message.text, "attachment": attachment}


def capabilities() -> dict:
    """What this installation can do right now, as the flyout needs to know it."""
    vision = False
    try:
        import mc_llm_runtime

        vision = bool(mc_llm_runtime.config().sees)
    except Exception:
        logger.debug("Model Chain: could not read the vision configuration", exc_info=True)
    voice = False
    try:
        import mc_voice_state

        voice = bool(mc_voice_state.enabled())
    except Exception:
        logger.debug("Model Chain: could not read the voice configuration", exc_info=True)
    return {"actions": list(ACTIONS), "vision": vision, "upload": True,
            "voice": voice, "streaming": True,
            "protocol_version": PROTOCOL_VERSION, "max_text_bytes": MAX_TEXT_BYTES}


def bootstrap(page_id: str = "") -> dict:
    """What a page needs before it can show anything, including *which* thread.

    The selection is the part that was missing, and without it the flyout had
    nothing to draw: it opened with an empty character and an empty thread, the
    snapshot call returned early because there was nothing to snapshot, and the
    panel sat on "Reconnecting…" for ever with a transcript it was never going
    to be given.

    It is a *seed* and not a source of truth -- ``mc_llm_state.remember()`` is
    installation-wide, so it says which conversation was last opened on this
    machine, not which one this page is looking at. The page owns its selection
    from here on (two windows may deliberately differ), and this is only how it
    starts out on the one the tab has open.
    """
    return {"protocol_version": PROTOCOL_VERSION, "server_epoch": SERVER_EPOCH,
            "server_time": time.time(), "capabilities": capabilities(),
            "page_id": page_id or uuid.uuid4().hex, "actions": list(ACTIONS),
            "selection": remembered_selection(),
            "characters": character_names(),
            "mode": remembered_mode(),
            "read_aloud": read_aloud()}


def read_aloud():
    """Whether replies are read aloud: Voice Chat's "Speak replies
    automatically", the one setting both views share. ``None`` if it cannot be
    read.

    The flyout's switch is drawn from this. It used to start "off" whatever the
    setting was and never ask, so a first press on a switch that read off
    turned on something already on -- and the replies went on being spoken.
    ``None`` rather than ``False`` when unreadable, because "off" is a claim and
    a switch that makes one it cannot back is the bug this replaces.
    """
    try:
        import mc_voice_state

        return bool(mc_voice_state.auto_speak())
    except Exception:
        logger.debug("Model Chain: could not read whether replies are read aloud",
                     exc_info=True)
        return None


def remembered_selection() -> dict:
    """The character and thread LLM Studio was last left on."""
    try:
        import mc_llm_state

        found = mc_llm_state.preferences()
        return {"character": str(found.get("character") or ""),
                "thread_id": str(found.get("thread") or "")}
    except Exception:
        logger.debug("Model Chain: could not read the remembered conversation",
                     exc_info=True)
        return {"character": "", "thread_id": ""}


def remembered_mode() -> str:
    try:
        import mc_llm_state

        return str(mc_llm_state.preferences().get("mode") or "")
    except Exception:
        return ""


def character_names() -> list:
    try:
        return list(_characters().names())
    except Exception:
        logger.debug("Model Chain: could not list characters", exc_info=True)
        return []


def threads(character: str) -> list:
    """The character's threads, most recently used first."""
    try:
        return [{"thread_id": info.identifier, "title": info.title,
                 "updated": info.updated}
                for info in chats().listing(str(character or ""))]
    except Exception:
        logger.debug("Model Chain: could not list threads for %s", character,
                     exc_info=True)
        return []


