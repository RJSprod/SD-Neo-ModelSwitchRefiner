def submit(body: dict, scope: str = DEFAULT_SCOPE) -> dict:
    """One command, from anywhere. The only entry point that writes.

    Returns the response of specification 6.7 rather than raising, because both
    callers -- a Gradio callback and an HTTP route -- have to turn a refusal
    into something on a screen and neither benefits from an exception crossing
    the boundary first.
    """
    try:
        envelope = parse(body)
    except Refused as refusal:
        return _failed(refusal, body.get("operation_id") if isinstance(body, dict) else None)
    return run(envelope, scope)


def run(envelope: Envelope, scope: str = DEFAULT_SCOPE) -> dict:
    """A validated envelope, executed exactly once."""
    try:
        record, fresh = registry.reserve(scope, envelope.operation_id, envelope.digest())
    except Refused as refusal:
        return _failed(refusal, envelope.operation_id)
    if not fresh:
        if record.state in (DONE, ACCEPTED):
            found = dict(record.outcome)
            found["duplicate"] = True
            return found
        if record.state == REFUSED:
            found = dict(record.outcome)
            found["duplicate"] = True
            return found
        return {"ok": True, "operation_id": envelope.operation_id, "phase": PENDING,
                "duplicate": True, "persisted": False, "server_epoch": SERVER_EPOCH}

    try:
        outcome = _dispatch(envelope, scope)
    except Refused as refusal:
        failure = _failed(refusal, envelope.operation_id)
        registry.settle(scope, envelope.operation_id, REFUSED, failure)
        return failure
    except StoreRefusal as refusal:
        failure = _failed(_from_store(refusal), envelope.operation_id)
        registry.settle(scope, envelope.operation_id, REFUSED, failure)
        return failure
    except Exception as exc:
        logger.warning("Model Chain: a conversation command failed", exc_info=True)
        failure = _failed(Refused(SAVE_FAILED, f"That could not be done: {exc}"),
                          envelope.operation_id)
        registry.settle(scope, envelope.operation_id, REFUSED, failure)
        return failure
    # Only a generating command leaves something running to pin a record for.
    # Everything else is finished the moment it returns, and a record settled as
    # ACCEPTED is pinned -- so settling a Stop or a rename that way would leave
    # a record that never expires and is not counted against the terminal cap
    # either, which is an unbounded one.
    live = envelope.action in GENERATING and outcome.get("phase") not in (None, "completed")
    registry.settle(scope, envelope.operation_id, ACCEPTED if live else DONE, outcome)
    return outcome


def _from_store(refusal: StoreRefusal) -> Refused:
    return Refused(getattr(refusal, "code", SAVE_FAILED), str(refusal),
                   **{key: value for key, value in (getattr(refusal, "detail", None) or {}).items()
                      if value is not None})


def _failed(refusal: Refused, operation_id) -> dict:
    return {"ok": False, "operation_id": str(operation_id or ""), "persisted": False,
            "duplicate": False, "phase": "failed", "server_epoch": SERVER_EPOCH,
            "error": refusal.payload(), "status": refusal.status}


def _accepted(envelope: Envelope, key: Key, revision: int, phase: str = "completed",
              persisted: bool = True, extra: dict | None = None) -> dict:
    found = {"ok": True, "operation_id": envelope.operation_id, "persisted": persisted,
             "duplicate": False, "phase": phase, "server_epoch": SERVER_EPOCH,
             "accepted_revision": envelope.expected_revision,
             "resulting_conversation": {"character": key.character,
                                        "thread_id": key.thread_id},
             "revision": revision}
    if extra:
        found.update(extra)
    return found


def _dispatch(envelope: Envelope, scope: str) -> dict:
    if envelope.action == STOP:
        return _stop(envelope)
    if envelope.action == CREATE_THREAD:
        return _create_thread(envelope)
    if envelope.action == DELETE_THREAD:
        return _delete_thread(envelope)
    if envelope.action == BRANCH:
        return _branch(envelope)
    if envelope.action in GENERATING:
        import mc_llm_conversation_ops as ops

        return ops.begin(envelope, scope)
    return _mutate(envelope)


# -- the plain content mutations -------------------------------------------- #


def _mutate(envelope: Envelope) -> dict:
    store = chats()
    key = envelope.conversation
    receipt = Receipt(operation_id=envelope.operation_id, action=envelope.action,
                      issued_at=envelope.issued_at, payload_digest=envelope.digest())

    def change(conversation):
        return _apply(envelope, conversation)

    committed = store_module.transaction(store, key, envelope.expected_revision, change,
                                         receipt=receipt)
    if committed.duplicate:
        return _accepted(envelope, key, committed.revision,
                         extra={"duplicate": True, "receipt": committed.receipt})
    return _accepted(envelope, key, committed.revision,
                     extra={"detail": committed.result if isinstance(committed.result, dict)
                            else None})


def _apply(envelope: Envelope, conversation) -> object:
    """One action, against the copy the transaction will write. May raise.

    Every branch validates its target against *this* conversation -- the one
    read under the lock -- rather than against whatever the caller described.
    That is the second half of the (index, revision) promise: the revision says
    the conversation has not moved, and this says the index names a message in
    it of the role the action applies to.
    """
    action = envelope.action
    if action == EDIT_MESSAGE:
        return _edit(envelope, conversation)
    if action == SELECT_VERSION:
        message = _message(envelope, conversation)
        wanted = envelope.target_version
        if wanted is None:
            raise Refused(INVALID_INPUT, "Which version?")
        if not 0 <= wanted < len(message.versions):
            raise Refused(INVALID_INPUT, "That version is not there any more.")
        message.show(wanted)
        return {"active": message.active, "versions": len(message.versions)}
    if action == DROP_VERSION:
        message = _message(envelope, conversation)
        if len(message.versions) <= 1:
            raise Refused(INVALID_INPUT,
                          "This message has only one version — deleting it would delete "
                          "the message.")
        message.drop_version()
        return {"active": message.active, "versions": len(message.versions)}
    if action == DELETE_MESSAGE:
        _message(envelope, conversation)
        conversation.delete(envelope.target_index)
        return {"removed": 1}
    if action == DELETE_FROM:
        _message(envelope, conversation)
        removed = len(conversation.messages) - envelope.target_index
        wanted = envelope.payload.get("confirm_count")
        if wanted is not None and wanted != removed:
            raise Refused(STALE_REVISION,
                          f"That would now delete {removed} messages, not {wanted}.")
        conversation.delete_from(envelope.target_index)
        return {"removed": removed}
    if action == RENAME_THREAD:
        title = (envelope.payload.get("title") or "").strip()
        if not title:
            raise Refused(INVALID_INPUT, "A thread needs a title.")
        conversation.title = title
        return {"title": title}
    if action == SET_RESPONSE_PREFIX:
        conversation.response_prefix = envelope.payload.get("prefix") or ""
        return {"prefix": conversation.response_prefix}
    if action == RESTORE_TO_DRAFT:
        return _restore_to_draft(envelope, conversation)
    raise Refused(INVALID_INPUT, f"{action} is not something this can do here.")


def _message(envelope: Envelope, conversation, role: str | None = None):
    index = envelope.target_index
    if index is None:
        raise Refused(INVALID_INPUT, "Which message?")
    if not 0 <= index < len(conversation.messages):
        raise Refused(STALE_REVISION, "That message is not there any more.")
    message = conversation.messages[index]
    if role is not None and message.role != role:
        raise Refused(INVALID_INPUT, "That action does not apply to this message.")
    return message


def _edit(envelope: Envelope, conversation) -> dict:
    """Edit one message in place, at any index, and say what it did.

    In place is the behaviour, unchanged (4.2): the words in the thread change,
    the thread stays where it is, and the replies that followed are still under
    it. Descendants are not regenerated and the editor says so -- a rewritten
    question with the old answer under it is a conversation somebody can then
    ask about, and silently re-running the model would be an edit that costs a
    GPU minute nobody asked for.
    """
    import mc_llm_attachments

    message = _message(envelope, conversation)
    version = envelope.target_version
    if version is not None:
        if not 0 <= version < len(message.versions):
            raise Refused(STALE_REVISION, "That version is not there any more.")
        message.active = version
    message.text = (envelope.payload.get("text") or "").strip()

    wanted = envelope.payload.get("image_action", KEEP)
    if wanted == REMOVE:
        message.image_path, message.image, message.image_name = "", "", ""
    elif wanted == REPLACE:
        token = envelope.payload.get("attachment_token") or ""
        import mc_llm_attachment_staging as staging

        staged = staging.resolve(token)
        if staged is None:
            raise Refused(ATTACHMENT_EXPIRED, "Attach this image again.")
        try:
            message.image_path = mc_llm_attachments.store(staged.image,
                                                          conversation.character)
        except Exception as exc:
            raise Refused(SAVE_FAILED, f"Could not keep that picture: {exc}")
        message.image = ""
        message.image_name = staged.name
    return {"index": envelope.target_index, "image_action": wanted}


def _restore_to_draft(envelope: Envelope, conversation) -> dict:
    """The unanswered-message lift, as a command somebody asked for.

    It already happened -- opening a thread that ended in an unanswered message
    took it out of the thread and put it back in the composer, and *saved*.
    Navigation wrote. That is kept, because it is what the owner asked for and
    people rely on it, but it is a command now: the read-only refresh that keeps
    a second window current can never reach it, which it could when it was a
    side effect of ``_open_thread``.
    """
    from prompt_master.chat.history import USER

    index = envelope.target_index
    if index is None or not 0 <= index < len(conversation.messages):
        raise Refused(STALE_REVISION, "That message is not there any more.")
    message = conversation.messages[index]
    if message.role != USER or index != len(conversation.messages) - 1:
        raise Refused(INVALID_INPUT, "Only an unanswered last message can be taken back.")
    if message.attached:
        raise Refused(INVALID_INPUT,
                      "This message carries a picture, so it stays in the thread. "
                      "Edit it, or send it again from here.")
    text = message.text
    conversation.delete_from(index)
    return {"text": text}


