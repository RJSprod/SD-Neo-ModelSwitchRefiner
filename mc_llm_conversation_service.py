_ID = re.compile(r"^[A-Za-z0-9_.:-]{1,128}$")
"""What an identifier may look like. Anything else is not one.

Applied to operation ids, page ids and thread ids alike. The characters left
out are the ones that mean something to a path or to a shell; the length bound
is what stops a megabyte of "id" reaching a dictionary key.
"""


def _text(value, field_name: str, limit: int = 4096) -> str:
    if value is None:
        return ""
    if not isinstance(value, str):
        raise Refused(INVALID_INPUT, f"{field_name} must be text.")
    if len(value.encode("utf-8")) > limit:
        raise Refused(INVALID_INPUT, f"{field_name} is too long.")
    return value


def _identifier(value, field_name: str, required: bool = True) -> str:
    found = _text(value, field_name, 256).strip()
    if not found:
        if required:
            raise Refused(INVALID_INPUT, f"{field_name} is required.")
        return ""
    if not _ID.match(found):
        raise Refused(INVALID_INPUT, f"{field_name} is not a valid identifier.")
    return found


@dataclass
class Envelope:
    """One command, validated into the shape the dispatcher can trust."""

    action: str
    operation_id: str
    conversation: Key | None = None
    expected_revision: object = None
    target_index: int | None = None
    target_version: int | None = None
    payload: dict = field(default_factory=dict)
    page_id: str = ""
    issued_at: str = ""
    selection_epoch: str = ""

    def digest(self) -> str:
        """What "the same request" means, for deduplication.

        Covers what the command *does* and nothing about who sent it: action,
        target, expected revision, settings and content. ``page_id`` and
        ``selection_epoch`` are deliberately outside it, so that a retry after
        a refresh -- which is a different page with the same intention -- is
        recognised as the same request rather than refused as a reused id.
        """
        material = {
            "action": self.action,
            "conversation": [self.conversation.character, self.conversation.thread_id]
            if self.conversation else None,
            "expected_revision": self.expected_revision,
            "target": [self.target_index, self.target_version],
            "payload": {key: self.payload[key] for key in sorted(self.payload)
                        if key not in ("selection_epoch",)},
        }
        raw = json.dumps(material, sort_keys=True, ensure_ascii=False, default=str)
        return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def parse(body: dict) -> Envelope:
    """One request body, validated. Raises :class:`Refused` and never guesses.

    Every branch below refuses rather than repairing. A field this does not
    understand is not ignored: an unknown key that changes meaning is exactly
    how a newer client's "and also delete the rest" would be silently dropped
    by an older server and read as a plain edit.
    """
    if not isinstance(body, dict):
        raise Refused(INVALID_INPUT, "The request was not an object.")

    version = body.get("protocol_version")
    if version != PROTOCOL_VERSION:
        raise Refused(UNSUPPORTED_PROTOCOL,
                      "This page is a different version from the server. Reload the page.")

    epoch = body.get("server_epoch")
    if epoch is not None and str(epoch) != SERVER_EPOCH:
        raise Refused(SERVER_RESTARTED,
                      "The server restarted. Reload the page to carry on.")

    unknown = set(body) - {"protocol_version", "server_epoch", "operation_id", "issued_at",
                           "page_id", "conversation", "expected_revision", "action",
                           "target", "payload", "selection_epoch"}
    if unknown:
        raise Refused(INVALID_INPUT,
                      f"The request carried fields this server does not understand: "
                      f"{', '.join(sorted(unknown))}.")

    action = _text(body.get("action"), "action", 64)
    if action not in ACTIONS:
        raise Refused(INVALID_INPUT, f"{action or 'That'} is not something this can do.")

    operation_id = _identifier(body.get("operation_id"), "operation_id")
    page_id = _identifier(body.get("page_id"), "page_id", required=False)
    issued_at = _text(body.get("issued_at"), "issued_at", 64)

    conversation = None
    raw_conversation = body.get("conversation")
    if raw_conversation is not None:
        if not isinstance(raw_conversation, dict):
            raise Refused(INVALID_INPUT, "conversation must be an object.")
        conversation = Key(
            character=_text(raw_conversation.get("character"), "character", 256),
            thread_id=_identifier(raw_conversation.get("thread_id"), "thread_id",
                                  required=action != CREATE_THREAD),
        )
    if conversation is None and action != CREATE_THREAD:
        raise Refused(INVALID_INPUT, "conversation is required.")
    if conversation is not None and not str(conversation.character or "").strip():
        raise Refused(INVALID_INPUT, "character is required.")

    expected = _expected(body.get("expected_revision"), action)
    index, version_at = _target(body.get("target"))
    payload = _payload(body.get("payload"), action)

    return Envelope(action=action, operation_id=operation_id, conversation=conversation,
                    expected_revision=expected, target_index=index,
                    target_version=version_at, payload=payload, page_id=page_id,
                    issued_at=issued_at,
                    selection_epoch=_text(body.get("selection_epoch"),
                                          "selection_epoch", 128))


def _expected(raw, action: str):
    """``expected_revision`` as a comparison token, or a refusal.

    ``None`` is allowed only where there is nothing yet to compare against:
    creating a thread, and stopping an operation, which does not write.
    Everywhere else an absent token would mean "write over whatever is there",
    which is the behaviour this whole module replaced.
    """
    if raw is None:
        if action in (CREATE_THREAD, STOP):
            return None
        raise Refused(INVALID_INPUT, "expected_revision is required.")
    if not isinstance(raw, dict):
        raise Refused(INVALID_INPUT, "expected_revision must be an object.")
    kind = raw.get("kind")
    if kind == "revision":
        value = raw.get("value")
        if isinstance(value, bool) or not isinstance(value, int) or value < 0:
            raise Refused(INVALID_INPUT, "expected_revision.value must be a revision.")
        return value
    if kind == "legacy":
        found = _text(raw.get("fingerprint"), "fingerprint", 256)
        if not found:
            raise Refused(INVALID_INPUT, "expected_revision.fingerprint is required.")
        return found
    raise Refused(INVALID_INPUT, "expected_revision.kind must be 'revision' or 'legacy'.")


def _target(raw):
    if raw is None:
        return None, None
    if not isinstance(raw, dict):
        raise Refused(INVALID_INPUT, "target must be an object.")
    index = raw.get("index")
    if isinstance(index, bool) or not isinstance(index, int) or index < 0:
        raise Refused(INVALID_INPUT, "target.index must be a message index.")
    version = raw.get("version")
    if version is not None and (isinstance(version, bool) or not isinstance(version, int)
                                or version < 0):
        raise Refused(INVALID_INPUT, "target.version must be a version number.")
    return index, version


def _payload(raw, action: str) -> dict:
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        raise Refused(INVALID_INPUT, "payload must be an object.")
    found: dict = {}
    if "text" in raw:
        found["text"] = _text(raw.get("text"), "text", MAX_TEXT_BYTES)
    if "attachment_token" in raw:
        found["attachment_token"] = _identifier(raw.get("attachment_token"),
                                                "attachment_token", required=False)
    if "image_action" in raw:
        chosen = _text(raw.get("image_action"), "image_action", 16)
        if chosen not in IMAGE_ACTIONS:
            raise Refused(INVALID_INPUT, "image_action must be keep, replace or remove.")
        found["image_action"] = chosen
    if "title" in raw:
        found["title"] = _text(raw.get("title"), "title", 4096)
    if "prefix" in raw:
        found["prefix"] = _text(raw.get("prefix"), "prefix", 16 * 1024)
    if "confirm_count" in raw:
        count = raw.get("confirm_count")
        if isinstance(count, bool) or not isinstance(count, int) or count < 0:
            raise Refused(INVALID_INPUT, "confirm_count must be a count.")
        found["confirm_count"] = count
    if "confirm_title" in raw:
        found["confirm_title"] = _text(raw.get("confirm_title"), "confirm_title", 4096)
    if "operation_id" in raw:
        found["operation_id"] = _identifier(raw.get("operation_id"), "operation_id",
                                            required=action == STOP)
    if "voice" in raw:
        found["voice"] = bool(raw.get("voice"))
    if "settings" in raw:
        found["settings"] = _settings(raw.get("settings"))
    unknown = set(raw) - set(found) - {"settings"}
    if unknown:
        raise Refused(INVALID_INPUT,
                      f"payload carried fields this server does not understand: "
                      f"{', '.join(sorted(unknown))}.")
    return found


def _settings(raw) -> dict:
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        raise Refused(INVALID_INPUT, "settings must be an object.")
    allowed = {"temperature", "top_p", "reply_tokens", "seed"}
    unknown = set(raw) - allowed
    if unknown:
        raise Refused(INVALID_INPUT,
                      f"settings carried fields this server does not understand: "
                      f"{', '.join(sorted(unknown))}.")
    found = {}
    for name in sorted(allowed & set(raw)):
        value = raw.get(name)
        if value is None:
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise Refused(INVALID_INPUT, f"settings.{name} must be a number.")
        found[name] = value
    return found


# --------------------------------------------------------------------------- #
# Deduplication
# --------------------------------------------------------------------------- #

PENDING = "pending"
ACCEPTED = "accepted"
DONE = "done"
REFUSED = "refused"


@dataclass
class Record:
    """What is known about one operation id in this process."""

    operation_id: str
    digest: str
    state: str = PENDING
    outcome: dict = field(default_factory=dict)
    settled: float = 0.0
    pinned: bool = False


class _Registry:
    """Operation ids and their outcomes, per access scope.

    Reserved *before* any mutation, which is the ordering the whole guarantee
    rests on: a second request carrying the same id finds the reservation and
    waits for or returns its answer, rather than racing it into the store.

    Checked before the revision comparison, deliberately (6.4). A retry of a
    request that was already accepted must not be told its revision is stale --
    it *is* stale, because the request itself is what moved it.
    """

    def __init__(self):
        self._guard = threading.Lock()
        self._scopes: dict[str, dict[str, Record]] = {}

    def reserve(self, scope: str, operation_id: str, digest: str) -> tuple[Record, bool]:
        """``(record, fresh)``. ``fresh`` is whether this caller owns the work."""
        with self._guard:
            records = self._scopes.setdefault(scope, {})
            self._expire(records)
            found = records.get(operation_id)
            if found is not None:
                if found.digest != digest:
                    raise Refused(OPERATION_ID_REUSED,
                                  "That request id has already been used for a different "
                                  "request.")
                return found, False
            terminal = sum(1 for record in records.values() if record.state in (DONE, REFUSED))
            if terminal >= MAX_TERMINAL_RECORDS:
                raise Refused(SERVICE_UNAVAILABLE,
                              "Too many recent requests are still being remembered. "
                              "Try again shortly.")
            record = records[operation_id] = Record(operation_id=operation_id, digest=digest,
                                                    pinned=True)
            return record, True

    def settle(self, scope: str, operation_id: str, state: str, outcome: dict) -> None:
        with self._guard:
            record = self._scopes.setdefault(scope, {}).get(operation_id)
            if record is None:
                return
            record.state = state
            record.outcome = outcome
            record.pinned = state == ACCEPTED
            record.settled = time.time()

    def find(self, scope: str, operation_id: str) -> Record | None:
        with self._guard:
            records = self._scopes.get(scope, {})
            self._expire(records)
            return records.get(operation_id)

    def drop(self, scope: str, operation_id: str) -> None:
        with self._guard:
            self._scopes.get(scope, {}).pop(operation_id, None)

    @staticmethod
    def _expire(records: dict) -> None:
        now = time.time()
        for key in [key for key, record in records.items()
                    if not record.pinned and record.settled
                    and now - record.settled > TERMINAL_RETENTION]:
            records.pop(key, None)

    def reset(self) -> None:
        """Drop every record. For the tests, and for a UI reload."""
        with self._guard:
            self._scopes.clear()


registry = _Registry()


DEFAULT_SCOPE = "local"
"""The access scope when the host has not told us about more than one.

Present as a parameter everywhere rather than assumed, because the day this
extension is put behind a multi-user proxy is the day an operation registry
shared between people becomes a way to read somebody else's reply.
"""


