def install(_demo=None, app=None) -> bool:
    """Register the routes on the WebUI's FastAPI app. Idempotent, never fatal.

    Signature is ``script_callbacks.on_app_started``'s. A UI reload calls it
    again and a second registration would give FastAPI two matching routes for
    one path, so the existing paths are looked for first -- the pattern
    ``mc_literal_report`` established and ``mc_voice_api`` follows.
    """
    global _installed

    if app is None or not hasattr(app, "add_api_route"):
        return False
    existing = {getattr(route, "path", None) for route in getattr(app, "routes", [])}
    if all(path in existing for path in ROUTES):
        _installed = True
        return True
    if Request is None:
        logger.debug("Model Chain: the conversation routes have no FastAPI to register on")
        return False

    async def bootstrap_route(request: Request):
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        try:
            return _json(bootstrap(request.query_params.get("page") or ""))
        except Exception:
            return _failed("could not start a conversation session",
                           "The conversation could not be reached.")

    async def commands_route(request: Request):
        try:
            checked(request)
            body = await _body(request)
        except Refused as exc:
            return _refusal(exc)
        try:
            payload, status = commands(body)
            return _json(payload, status)
        except Exception:
            return _failed("a conversation command failed", "That could not be done.")

    async def snapshot_route(request: Request):
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        query = request.query_params
        cursor = query.get("cursor")
        try:
            return _json(snapshot(query.get("character") or "", query.get("thread") or "",
                                  query.get("selection_epoch") or "",
                                  int(cursor) if cursor not in (None, "") else None))
        except Exception:
            return _failed("could not read a conversation",
                           "This conversation could not be read.")

    async def operation_route(request: Request):
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        try:
            payload, status = operation(request.path_params.get("operation_id", ""))
            return _json(payload, status)
        except Exception:
            return _failed("could not read an operation", "That could not be looked up.")

    async def resolve_route(request: Request):
        try:
            checked(request)
            body = await _body(request)
        except Refused as exc:
            return _refusal(exc)
        import mc_llm_conversation_ops as ops

        try:
            return _json(ops.resolve(request.path_params.get("operation_id", ""),
                                     str(body.get("decision") or "")))
        except service.Refused as refusal:
            return _json({"ok": False, "error": refusal.payload()}, refusal.status)
        except Exception:
            return _failed("could not resolve an unsaved reply",
                           "That reply could not be dealt with.")

    async def subscribe_route(request: Request):
        try:
            checked(request)
            body = await _body(request)
        except Refused as exc:
            return _refusal(exc)
        try:
            return _json(subscribe(str(body.get("page_id") or "")))
        except Exception:
            return _failed("could not open a conversation feed",
                           "Live updates could not be started.")

    async def events_route(request: Request):
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        query = request.query_params
        found = feed.find(query.get("feed") or "")
        if found is None:
            return _json({"ok": False, "error": {"code": service.SERVER_RESTARTED,
                                                 "message": "This feed is gone. Subscribe "
                                                            "again.", "retryable": False}},
                         409)
        cursor = query.get("cursor")
        if cursor not in (None, ""):
            try:
                found.cursor = int(cursor)
            except (TypeError, ValueError):
                pass

        def body():
            # A comment line on every idle pass. Proxies close connections that
            # say nothing, and two bytes every fifteen seconds is the cheapest
            # way to be sure a silence is ours rather than the network's.
            quiet = time.monotonic()
            yield b": open\n\n"
            for event in found.events(idle=STREAM_IDLE):
                quiet = time.monotonic()
                yield f"event: {event.get('kind')}\n".encode("utf-8")
                yield f"id: {event.get('stream_cursor')}\n".encode("utf-8")
                yield f"data: {json.dumps(event, ensure_ascii=False)}\n\n".encode("utf-8")
                if time.monotonic() - quiet > HEARTBEAT:
                    yield b": keep-alive\n\n"

        return StreamingResponse(body(), media_type="text/event-stream",
                                 headers={"Cache-Control": "no-cache, no-transform",
                                          "X-Accel-Buffering": "no",
                                          "Connection": "keep-alive"})

    async def attachments_route(request: Request):
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        try:
            form = await request.form()
            upload = form.get("file")
            if upload is None:
                return _json({"ok": False, "error": {"code": service.INVALID_INPUT,
                                                     "message": "No picture was sent.",
                                                     "retryable": False}}, 400)
            raw = await upload.read()
            payload, status = stage_upload(raw, getattr(upload, "filename", "") or "")
            return _json(payload, status)
        except Exception:
            return _failed("could not stage an attachment",
                           "That picture could not be read.")

    async def attachment_delete_route(request: Request):
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        import mc_llm_attachment_staging as staging

        return _json({"ok": staging.discard(request.path_params.get("token", ""))})

    async def workspaces_route(request: Request):
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        return _json(workspaces())

    async def served_route(request: Request):
        """One stored picture, by ticket. The flyout's transcript reads these.

        A ticket rather than a path, because specification 6.6 is explicit that
        no filesystem path leaves the server -- and a route that took one would
        be a route somebody could hand a different one.
        """
        try:
            checked(request)
        except Refused as exc:
            return _refusal(exc)
        import mc_llm_attachments

        found = mc_llm_attachments.serving_path(request.path_params.get("ticket", ""))
        if found is None:
            return _json({"ok": False, "error": {"code": service.NOT_FOUND,
                                                 "message": "That picture is not there.",
                                                 "retryable": False}}, 404)
        try:
            return Response(content=found.read_bytes(),
                            media_type=_media_type(found.suffix),
                            headers={"Cache-Control": "private, max-age=3600"})
        except OSError:
            return _failed("could not read an attachment", "That picture could not be read.",
                           404)

    try:
        for path, handler, methods in (
                (BOOTSTRAP_ROUTE, bootstrap_route, ["GET"]),
                (COMMANDS_ROUTE, commands_route, ["POST"]),
                (SNAPSHOT_ROUTE, snapshot_route, ["GET"]),
                (OPERATION_ROUTE, operation_route, ["GET"]),
                (RESOLVE_ROUTE, resolve_route, ["POST"]),
                (SUBSCRIBE_ROUTE, subscribe_route, ["POST"]),
                (EVENTS_ROUTE, events_route, ["GET"]),
                (ATTACHMENTS_ROUTE, attachments_route, ["POST"]),
                (ATTACHMENT_ROUTE, attachment_delete_route, ["DELETE"]),
                (WORKSPACES_ROUTE, workspaces_route, ["GET"]),
                (SERVED_ROUTE, served_route, ["GET"])):
            if path not in existing:
                app.add_api_route(path, handler, methods=methods)
    except Exception:
        logger.debug("Model Chain: could not register the conversation routes", exc_info=True)
        return False
    _installed = True
    logger.info("Model Chain: Forge Assistant conversation routes registered at %s", PREFIX)
    return True


def _media_type(suffix: str) -> str:
    return {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
            ".webp": "image/webp", ".gif": "image/gif"}.get(suffix.lower(),
                                                            "application/octet-stream")


def installed() -> bool:
    return _installed
